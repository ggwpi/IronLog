// Compile the pinned, unchanged upstream converter for the API's legacy-client boundary.
// The API Docker context cannot import frontend sources. Never edit the generated algorithm.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'
import { rolldown } from '../frontend/node_modules/rolldown/dist/index.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = resolve(root, 'frontend/src/lib/opengym-v145/session-engine/frontend/src/lib/units.js').replaceAll('\\', '/')
const bytes = readFileSync(source)
const manifest = JSON.parse(readFileSync(resolve(root, 'frontend/src/lib/opengym-v145/session-engine/source-blobs.json')))
const blob = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex')
const expected = manifest['frontend/src/lib/units.js'] ?? manifest.files?.['frontend/src/lib/units.js']
if (blob !== expected) throw new Error('Pinned upstream units source differs from its manifest')
const bundle = await rolldown({ cwd: root, input: 'body-sync-entry', treeshake: { moduleSideEffects: false }, plugins: [{
  name: 'pinned-body-converter',
  resolveId(id, importer) {
    if (id === 'body-sync-entry') return '\0body-sync-entry'
    if (id === source) return source
    if (importer?.replaceAll('\\', '/').toLowerCase() === source.toLowerCase() && id.startsWith('.')) return { id, external: true, moduleSideEffects: false }
  },
  load(id) { if (id === '\0body-sync-entry') return `export { convertBodyWeight } from ${JSON.stringify(source)}` },
}], preserveEntrySignatures: 'strict' })
const { output: chunks } = await bundle.generate({ format: 'es' })
await bundle.close()
// Rolldown also lists tree-shaken externals in chunk.imports; validate the emitted module itself.
if (chunks.length !== 1 || chunks[0].type !== 'chunk' || /\bimport\b|\bfrom\s+["']/.test(chunks[0].code) || chunks[0].code.length > 2000) throw new Error('Body converter must be a standalone pure module')
const generated = `// Generated by scripts/build-body-sync-assets.mjs from openGym v1.4.5.\n// Original units.js Git blob: ${blob}. Do not edit.\n${chunks[0].code}`
const target = resolve(root, 'api/body-compat/units.js')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Body sync converter is stale')
} else { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, generated) }
console.log('Pinned body sync converter verified')
